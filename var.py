#Variáveis e tipos de Dados 
#Uma variável é um espaço na memória do computador que armazena um valor. 
# Cada variável tem um nome e um tipo de dado associado a ela.

nome = "Gabriel" #String , texto
idade = 20 #Int ,inteiro
altura = 1.87 #Float, decimal
ativo = True #Booleano, verdadeiro ou falso

print(f"nome: {nome}, idade: {idade}, altura: {altura}, ativo: {ativo}")
#f Strings são uma forma de formatar strings em Python, permitindo a inclusão de variáveis dentro de uma string usando chaves {}.

